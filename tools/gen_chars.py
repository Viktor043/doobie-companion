CHARS = [("BOSSY", "BO", BOSSY), ("EXQUISITE", "EX", POSH), ("BALKAN", "BK", BALKAN)]


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "firmware", "doobie", "chars.h")
    ok = True
    lines = ["#pragma once", "// GENERATED by tools/gen_chars.py -- edit the lines there, not here.",
             "// Character attitudes: BOSSY, EXQUISITE (Victorian), BALKAN. 200 lines each.", ""]
    for name, tag, pack in CHARS:
        total = sum(len(v) for v in pack.values())
        bad = [s for v in pack.values() for s in v if len(s) > 36 or any(ord(c) > 127 for c in s) or s != s.upper()]
        dups = {s for v in pack.values() for s in v if sum(x == s for vv in pack.values() for x in vv) > 1}
        print(f"{name:10s} {total} lines" + (f"  TOO LONG/BAD: {bad}" if bad else "") + (f"  DUPLICATES: {dups}" if dups else ""))
        if total != 200 or bad or dups:
            ok = False
        lines.append(f"// ---- {name}")
        for ev, items in pack.items():
            assert ev in EVENT_ORDER, ev
            body = ", ".join('"%s"' % s.replace('"', '\\"') for s in items)
            lines.append(f"static const char *const {tag}_{ev}[] = {{ {body} }};")
        lines.append("")
    lines.append("static const Pool CHARS[3][EV_COUNT] = {")
    for name, tag, pack in CHARS:
        row = ", ".join(f"POOL({tag}_{ev})" if ev in pack else "NOPOOL" for ev in EVENT_ORDER)
        lines.append(f"  /* {name} */ {{ {row} }},")
    lines.append("};")
    lines.append("")
    lines.append("// pet names per character: [char][0 he, 1 she, 2 other/kid][4]")
    lines.append("static const char *const CHAR_PET[3][3][4] = {")
    lines.append('  { { "INTERN", "ROOKIE", "TEAM", "CHAMP" }, { "INTERN", "ROOKIE", "TEAM", "CHAMP" }, { "INTERN", "ROOKIE", "TEAM", "CHAMP" } },')
    lines.append('  { { "GOOD SIR", "MY LORD", "OLD CHAP", "SIR" }, { "MY LADY", "MADAM", "DEAR LADY", "MILADY" }, { "DEAR FRIEND", "DEAREST", "MY DEAR", "GOOD SOUL" } },')
    lines.append('  { { "BRATE", "BRO", "LEGENDO", "MAJSTORE" }, { "SESTRO", "ZLATO", "SISTER", "LEGENDO" }, { "BRATE", "LEGENDO", "ZLATO", "DRUZE" } },')
    lines.append("};")
    if not ok:
        print("NOT WRITTEN: fix the issues above")
        sys.exit(1)
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
